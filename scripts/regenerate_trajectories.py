#!/usr/bin/env python3
"""Generate trajectories against the Lima VM, and measure what that buys.

    python3 scripts/regenerate_trajectories.py --measure
    python3 scripts/regenerate_trajectories.py --measure --observe 40 --repeats 2
    python3 scripts/regenerate_trajectories.py --out <dir> --repeats 6

Two of the operator's asks turn out to be one piece of engineering. The
trajectory corpus was generated by running the agent against *this Mac*, which
is why it carries this machine's MAC addresses, its global IPv6 address and its
ISP-delegated /64 — a privacy leak — and also why the model learns *this*
service list instead of how to read a service list — a generalisation problem.
``generate_trajectories`` already has the seam: pass ``host_executor`` and the
host worlds run somewhere else. ``lab/vm/adapter.py`` drives a real Lima VM over
SSH, so that is what this passes in.

``training/trajectories.py`` is not modified. The executor goes in through the
parameter that exists for it.

**The two axes are measured separately, and they are not the same problem.**
Privacy is satisfied by *any* substitution. Generalisation is satisfied only by
a *varied* one. A single-token redaction passes the privacy gate and makes the
model worse, so this reports both: host-identifier occurrences (privacy) and
distinct-literal count with maximum document frequency (generalisation). A
change that improves the first and not the second is reported as exactly that.

**And it reports the VM's own identifiers.** If VM trajectories carry
``lima-whetstone-lab`` 24 times instead of this Mac's hostname, that is progress
on privacy — it is not his machine — and it is *not* progress on
generalisation, because it is still one machine. The distinction matters enough
to print.

Three VM gotchas are already paid for and are handled here rather than
rediscovered:

* A file-overwrite technique (T1574.010) is caught by auditd only with a
  ``-w <path> -p wa`` **file watch**. An execve rule never sees it. The watch is
  loaded from ``AUDIT_RULE_ARGV`` imported from the adapter, not respelled here:
  the adapter's own comment says two copies of that rule that drifted would make
  the before/after meaningless while still printing a number.
* ``ausearch -ts recent`` **silently misses records** when the ``vz`` guest's RTC
  has skewed. So nothing here calls ``ausearch``; the preflight reads raw
  ``/var/log/audit/audit.log`` and compares the newest ``audit(EPOCH`` stamp to
  the guest's own ``date +%s``, and prints the skew.
* The audit log **persists across runs**, so a stale record from the last run
  reads as a detection this run. It is truncated per run.

**It never deletes.** ``training.trajectories._write_dir`` begins by unlinking
every ``trajectory-*.txt`` in its output directory, which against an existing
generation is a corpus delete. So this script writes the files itself, with the
same ``trajectory-NNNNN.txt`` contract, and refuses an output directory that
already holds any. The one thing it does truncate is the VM's own audit log,
which is lab telemetry on a disposable guest and is named in the plan.

No identifier is ever printed or written. Findings are ``kind len=<n>
sha256=<8 hex>``, the same fingerprint spelling ``training/corpus/verify.py``
uses.
"""


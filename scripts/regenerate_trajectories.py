def authored_literals(repo: Path = REPO) -> tuple[set[str], str]:
    """Every string this codebase *authors*, plus the whole tree as one blob.

    The discriminator between structure and host content. A literal present in
    the source is a fixture: it is byte-identical on every machine and teaches
    the model the shape of an observation. A literal that is nowhere in the
    source came from the machine the agent ran against, and that is the half
    that memorises.

    Two traps this is built around, both already paid for by the audit:

    ``ast`` as well as a substring test, because a string written as implicit
    concatenation across two source lines never matches contiguously in the raw
    text — that one put 5.85MB on the wrong side of the ledger and moved a
    headline by six points.

    ``os.walk(followlinks=False)``, never ``rglob``: this repository has a
    ``data`` symlink to the SSD, and following it once pulled the corpus cache
    back in as prose. The corpus ate itself and only the balance report caught
    it.
    """
    consts: set[str] = set()
    chunks: list[str] = []
    for base, dirs, names in os.walk(repo, followlinks=False):
        dirs[:] = sorted(d for d in dirs
                         if d not in {"__pycache__", ".git", ".pytest_cache",
                                      ".ruff_cache", "_site"}
                         and not (Path(base) / d).is_symlink())
        for name in sorted(names):
            if not name.endswith((".py", ".md", ".yaml", ".yml", ".json",
                                  ".sh", ".txt", ".toml")):
                continue
            path = Path(base) / name
            if path.is_symlink():
                continue
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            chunks.append(text)
            if name.endswith(".py"):
                try:
                    tree = ast.parse(text)
                except SyntaxError:
                    continue
                for node in ast.walk(tree):
                    if isinstance(node, ast.Constant) and isinstance(
                            node.value, str):
                        consts.add(node.value)
    return consts, "\n".join(chunks)


@dataclass
class Spread:
    """The generalisation numbers for one batch of documents."""

    documents: int = 0
    chars: int = 0
    segments: int = 0
    malformed: int = 0
    distinct: int = 0
    occurrences: int = 0
    host_distinct: int = 0
    host_occurrences: int = 0
    max_docfreq: float = 0.0
    max_docfreq_fp: str = ""
    top: list[tuple[str, int, int]] = field(default_factory=list)

    @property
    def mean_repetition(self) -> float:
        return self.host_occurrences / self.host_distinct if self.host_distinct else 0.0


def _leaves(obj: Any, out: list[str]) -> None:
    if isinstance(obj, dict):
        for value in obj.values():
            _leaves(value, out)
    elif isinstance(obj, list):
        for value in obj:
            _leaves(value, out)
    elif isinstance(obj, str):
        out.append(obj)
    elif isinstance(obj, (int, float)) and not isinstance(obj, bool):
        out.append(str(obj))


def spread(texts: Sequence[str], *, consts: set[str], blob: str,
           minlen: int = MIN_LITERAL) -> Spread:
    """Distinct literals, occurrences and the maximum document frequency.

    The generalisation number is ``max_docfreq`` over *host-read* literals.
    Over all literals it is meaningless: ``127.0.0.1`` is the authored target
    of every episode and sits at 100% of documents in every batch, which is
    structure doing its job. A privacy fix that maps 253 host literals onto one
    placeholder drives host occurrences to zero and leaves this number at its
    ceiling — which is precisely how a single-token redaction passes the
    privacy gate and makes the model worse.
    """
    docfreq: collections.Counter = collections.Counter()
    occ: collections.Counter = collections.Counter()
    out = Spread(documents=len(texts), chars=sum(len(t) for t in texts))
    for text in texts:
        here: set[str] = set()
        parts = SEGMENT.split(text)
        for i in range(1, len(parts) - 1, 2):
            name, body = parts[i], parts[i + 1].strip()
            if name not in JSON_SEGMENTS:
                continue
            out.segments += 1
            if not body.startswith(("{", "[")):
                continue
            try:
                parsed = json.loads(body)
            except json.JSONDecodeError:
                out.malformed += 1
                continue
            found: list[str] = []
            _leaves(parsed, found)
            for value in found:
                if len(value) >= minlen:
                    here.add(value)
                    occ[value] += 1
        for value in here:
            docfreq[value] += 1
    out.distinct = len(docfreq)
    out.occurrences = sum(occ.values())

    host = {}
    for value, docs in docfreq.items():
        # MAX_VALUE truncation appends U+2026, so a 221-character observation
        # no longer substring-matches its own source literal. Probe the
        # untruncated head too rather than counting it as host-read.
        probe = value[:-1] if value.endswith(ELLIPSIS) else value
        if probe in consts or probe in blob:
            continue
        host[value] = docs
    out.host_distinct = len(host)
    out.host_occurrences = sum(occ[v] for v in host)
    if host and texts:
        ranked = sorted(host.items(), key=lambda kv: (-kv[1], kv[0]))
        out.max_docfreq = 100.0 * ranked[0][1] / len(texts)
        out.max_docfreq_fp = fingerprint("literal", ranked[0][0])
        out.top = [(fingerprint("literal", v), d, occ[v])
                   for v, d in ranked[:10]]
    return out



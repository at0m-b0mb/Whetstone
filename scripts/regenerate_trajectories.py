def _run(argv: Sequence[str], *, timeout: int = 60) -> tuple[int, str, str]:
    """Run a host command. A timeout is mandatory and finite, as everywhere."""
    try:
        proc = subprocess.run(list(argv), capture_output=True, text=True,
                              timeout=timeout, errors="replace",
                              env={**os.environ, "LIMA_HOME": LIMA_HOME})
    except FileNotFoundError:
        return 127, "", f"{argv[0]} not found"
    except subprocess.TimeoutExpired:
        return -1, "", f"timed out after {timeout}s"
    return proc.returncode, proc.stdout, proc.stderr


def _run_on_guest(argv: Sequence[str], *,
                  timeout: int = 60) -> tuple[int, str, str]:
    """One argv list on the guest. No shell on either side of the boundary."""
    return _run(["limactl", "shell", "--workdir", "/", VM_NAME, "--", *argv],
                timeout=timeout)


def vm_state() -> str:
    """``Running``, ``Stopped``, or ``absent``, from ``limactl list``."""
    rc, out, _ = _run(["limactl", "list", "--format", "json"], timeout=60)
    if rc != 0:
        return "absent"
    for line in out.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if row.get("name") == VM_NAME:
            return str(row.get("status", "unknown"))
    return "absent"


def lima_home_available() -> tuple[bool, str]:
    """Whether LIMA_HOME is reachable, and what to say when it is not.

    ``LIMA_HOME`` defaults onto the external SSD, so when that drive drops off
    ``limactl list`` reports "No instance found" — which reads as *the VM was
    never created* and sends you off to create a second one. The drive
    disconnected once during this work and that is exactly the message it
    produced. Diagnosing it here costs four lines.
    """
    home = Path(LIMA_HOME)
    if home.exists():
        return True, ""
    missing = home
    probe = home
    while probe != probe.parent and not probe.exists():
        missing = probe
        probe = probe.parent
    if missing.parent == Path("/Volumes"):
        return False, (f"LIMA_HOME={LIMA_HOME} is on the volume "
                       f"{missing.name!r}, which is not mounted. limactl will "
                       f"report 'No instance found'; that is the drive, not a "
                       f"missing VM. Reconnect it and re-run.")
    return False, f"LIMA_HOME={LIMA_HOME} does not exist ({missing} is missing)."


def ensure_vm(*, start: bool) -> str:
    """Make sure the lab VM is up, starting it when allowed."""
    ok, why = lima_home_available()
    if not ok:
        raise SystemExit(why)
    state = vm_state()
    if state == "Running":
        return state
    if state == "absent":
        raise SystemExit(
            f"lab VM {VM_NAME!r} does not exist under LIMA_HOME={LIMA_HOME}. "
            f"Create it with:\n  LIMA_HOME={LIMA_HOME} limactl start "
            f"lab/vm/whetstone-lab.yaml")
    if not start:
        raise SystemExit(f"lab VM {VM_NAME!r} is {state} and --no-start was "
                         f"given")
    print(f"  starting {VM_NAME} (it was {state})")
    rc, _, err = _run(["limactl", "start", VM_NAME], timeout=300)
    if rc != 0:
        raise SystemExit(f"limactl start failed: {err.strip()[:200]}")
    return vm_state()


@dataclass
class Preflight:
    """What the guest's telemetry was doing before a single episode ran."""

    guest_epoch: int = 0
    host_epoch: int = 0
    newest_record: float = 0.0
    log_bytes_before: int = 0
    truncated: bool = False
    rule_loaded: bool = False
    rules: str = ""
    notes: list[str] = field(default_factory=list)

    @property
    def clock_skew(self) -> int:
        return self.guest_epoch - self.host_epoch

    @property
    def record_skew(self) -> float:
        if not self.newest_record or not self.guest_epoch:
            return 0.0
        return self.newest_record - self.guest_epoch


def _newest_audit_stamp(text: str) -> float:
    """The newest ``audit(EPOCH.mmm:ser)`` stamp in raw audit log text.

    Raw log rather than ``ausearch``: ``ausearch -ts recent`` computes its
    window from the guest's clock and silently returns nothing when the ``vz``
    guest's RTC has skewed — a missing record reads as "the control was silent",
    which is the one conclusion this whole lab exists to make honestly.
    """
    newest = 0.0
    for stamp in re.findall(r"audit\((\d+)\.(\d+):\d+\)", text):
        newest = max(newest, float(f"{stamp[0]}.{stamp[1]}"))
    return newest


def preflight(*, truncate: bool, arm: bool) -> Preflight:
    """Measure the guest's clock and telemetry, then arm it for this run."""
    pf = Preflight(host_epoch=int(time.time()))
    rc, out, _ = _run_on_guest(["date", "+%s"], timeout=30)
    if rc == 0 and out.strip().isdigit():
        pf.guest_epoch = int(out.strip())
    else:
        pf.notes.append("could not read the guest clock")

    rc, out, _ = _run_on_guest(
        ["sudo", "-n", "stat", "-c", "%s", GUEST_AUDIT_LOG], timeout=30)
    if rc == 0 and out.strip().isdigit():
        pf.log_bytes_before = int(out.strip())
    rc, out, _ = _run_on_guest(
        ["sudo", "-n", "tail", "-c", "65536", GUEST_AUDIT_LOG], timeout=60)
    if rc == 0:
        pf.newest_record = _newest_audit_stamp(out)
    if pf.record_skew and abs(pf.record_skew) > 120:
        pf.notes.append(
            "the newest audit record is %+.0fs from the guest's own clock: "
            "ausearch -ts recent would silently miss records in this state, "
            "which is why nothing here calls it" % pf.record_skew)

    if truncate:
        # Truncate, not rotate and not delete: the file keeps its inode, its
        # mode and auditd's open handle. A stale record from the last run reads
        # as a detection fired by this one, which is a false negative for the
        # gap the loop exists to find.
        rc, _, err = _run_on_guest(
            ["sudo", "-n", "truncate", "-s", "0", GUEST_AUDIT_LOG], timeout=30)
        pf.truncated = rc == 0
        if rc != 0:
            pf.notes.append(f"could not truncate the audit log: "
                            f"{err.strip()[:120]}")

    if arm:
        try:
            from lab.vm.adapter import AUDIT_RULE_ARGV
        except Exception as exc:                            # noqa: BLE001
            pf.notes.append(f"no AUDIT_RULE_ARGV to load ({exc})")
        else:
            # The watch, loaded from the adapter's own definition. A file
            # overwrite is invisible to an execve rule; only -w <path> -p wa
            # sees it, and a second spelling of that rule here would make the
            # armed-by-hand and armed-by-the-agent runs incomparable while
            # still printing a number.
            _run_on_guest(["sudo", "-n", "auditctl", *AUDIT_RULE_ARGV],
                          timeout=30)
            rc, out, _ = _run_on_guest(["sudo", "-n", "auditctl", "-l"],
                                       timeout=30)
            pf.rules = out.strip()
            pf.rule_loaded = rc == 0 and AUDIT_RULE_ARGV[1] in out
            if not pf.rule_loaded:
                pf.notes.append("the file watch is NOT loaded; a T1574.010 "
                                "overwrite will read as undetected")
    return pf



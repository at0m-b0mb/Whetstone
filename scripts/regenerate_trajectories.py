def write_trajectories(out: Path, texts: Sequence[str]) -> int:
    """``trajectory-NNNNN.txt`` per episode, refusing a directory with any.

    The contract is the filename: ``training/sft.py`` and
    ``training/corpus/sources/trajectories.py`` both glob for it. The refusal
    is this script's own rule — ``_write_dir`` in ``training/trajectories.py``
    unlinks every existing ``trajectory-*.txt`` first, which against an
    existing generation is a corpus delete, and that decision is the operator's
    and not a script's.
    """
    out.mkdir(parents=True, exist_ok=True)
    existing = sorted(out.glob("trajectory-*.txt"))
    if existing:
        raise SystemExit(
            f"{out} already holds {len(existing):,} trajectory-*.txt files. "
            f"This script will not delete them. Point --out at a new "
            f"directory, or move that generation aside with "
            f"scripts/quarantine_corpus.py.")
    for i, text in enumerate(texts):
        (out / f"trajectory-{i:05d}.txt").write_text(text, encoding="utf-8")
    return len(texts)



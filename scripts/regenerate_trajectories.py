from whetstone.paths import lima_home  # noqa: E402

LIMA_HOME = str(lima_home())
VM_NAME = os.environ.get("WHETSTONE_LAB_VM", "whetstone-lab")
GUEST_AUDIT_LOG = "/var/log/audit/audit.log"

#: Trajectory documents are a marker protocol, not JSON. These four segments
#: carry JSON bodies and are where every observed literal lives.
SEGMENT = re.compile(r"<\|([a-z]+)\|>")
JSON_SEGMENTS = {"act", "obs", "gate", "find"}

#: What ``whetstone/kernel/render.py`` appends at MAX_VALUE. Written as the
#: escape rather than the character so it is visible in a diff: a value
#: truncated at 220 characters arrives 221 long and stops substring-matching
#: its own source literal, which moved a measured headline by two points once.
ELLIPSIS = "\u2026"

#: A literal shorter than this is a word, not an identifier, and counting
#: "true" as a memorised host value buries the real findings — the mistake an
#: uncalibrated scanner over a 625MB security corpus makes first.
MIN_LITERAL = 5

C = {"dim": "\033[2m", "b": "\033[1m", "g": "\033[32m", "y": "\033[33m",
     "r": "\033[31m", "c": "\033[36m", "x": "\033[0m"}


def fingerprint(kind: str, value: str) -> str:
    return "%s len=%d sha256=%s" % (
        kind, len(value), hashlib.sha256(value.encode("utf-8")).hexdigest()[:8])



class Needles:
    """Identifiers that must not reach a corpus. Read from an OS, never stored.

    ``__repr__`` and ``__str__`` report counts by kind and nothing else, and a
    test asserts it — because the audit that found these leaks wrote its own
    needle table to a JSON file and then reported that it had not.
    """

    __slots__ = ("_pairs", "label")

    def __init__(self, pairs: Sequence[tuple[str, str]], label: str) -> None:
        self._pairs = tuple(pairs)
        self.label = label

    def __repr__(self) -> str:
        kinds: dict[str, int] = {}
        for kind, _ in self._pairs:
            kinds[kind] = kinds.get(kind, 0) + 1
        inner = ", ".join(f"{k}={v}" for k, v in sorted(kinds.items()))
        return f"<Needles {self.label}: {len(self._pairs)} needles [{inner}]>"

    __str__ = __repr__

    def __len__(self) -> int:
        return len(self._pairs)

    def __iter__(self):
        return iter(self._pairs)


def _ifconfig_needles(text: str) -> list[tuple[str, str]]:
    """MACs, global IPv6 addresses and their /64 prefixes out of link output.

    Only ``is_global`` addresses. ``fe80::`` is identical on every machine on
    the planet, and ``2001:db8::/32`` is in this corpus thousands of times *on
    purpose* — counting either as a leak is how a scanner produces a thousand
    findings and tells you nothing.
    """
    out: list[tuple[str, str]] = []
    for mac in sorted(set(re.findall(
            r"\b(?:ether|link/ether) ([0-9a-f:]{17})\b", text))):
        out.append(("mac", mac))
    prefixes: set[str] = set()
    for raw in sorted(set(re.findall(r"\binet6 ([0-9a-fA-F:]+)", text))):
        try:
            addr = ipaddress.IPv6Address(raw)
        except ValueError:
            continue
        if not addr.is_global:
            continue
        out.append(("ipv6-global", str(addr)))
        net = ipaddress.IPv6Network((addr, 64), strict=False)
        prefixes.add(str(net.network_address).rstrip("0").rstrip(":"))
    for pfx in sorted(prefixes):
        if len(pfx) >= 8:
            out.append(("ipv6-prefix64", pfx))
    return out


def host_needles() -> Needles:
    """This Mac's identifiers: the identity table's literals, plus the network.

    The identity layer comes through ``identity_leaks``, the public function, so
    this script does not pin another module's internals. The network layer is
    here because the identity table has none — and the identifiers it covers are
    the ones he cannot change. A NIC address is hardware-derived.
    """
    pairs: list[tuple[str, str]] = []
    try:
        from training.trajectories import identity_leaks

        pairs += [("identity", form) for form in identity_leaks(_identity_probe())]
    except Exception:                                       # noqa: BLE001
        pass
    for argv in (["/sbin/ifconfig"], ["ip", "-o", "addr"]):
        text = _run(argv, timeout=20)[1]
        if text:
            pairs += _ifconfig_needles(text)
            break
    return Needles(pairs, "this machine")


def _identity_probe() -> str:
    """A document made of this machine's own identifiers, for the table to read.

    ``identity_leaks`` answers "which of my literals are in this text", so the
    only way to enumerate the table through the public API is to hand it a text
    assembled from the same OS reads the table is built from.
    """
    import getpass
    import glob
    import platform
    import socket
    import tempfile

    names = {getpass.getuser(), socket.gethostname(), platform.node(),
             str(Path.home()), tempfile.gettempdir()}
    names.update(glob.glob("/var/folders/*/*/T"))
    try:
        import pwd

        names.add(pwd.getpwuid(os.getuid()).pw_gecos.split(",")[0].strip())
    except Exception:                                       # noqa: BLE001
        pass
    for name in list(names):
        if name and "." in name and not name.startswith("/"):
            names.add(name.partition(".")[0])
        if name and name.startswith("/"):
            names.add(str(Path(name).resolve()))
    return "\n".join(sorted(n for n in names if n))


def guest_needles() -> Needles:
    """The VM's own identifiers, fingerprinted exactly like the Mac's.

    Measured, not assumed. The point of the comparison is that *swapping which*
    machine is leaking is a privacy result and not a generalisation one, and
    that claim is only worth making with a number behind it.
    """
    pairs: list[tuple[str, str]] = []
    rc, out, _ = _run_on_guest(
        ["sh", "-c", "hostname; whoami; echo $HOME; cat /etc/machine-id "
                     "2>/dev/null; ip -o link; ip -o -6 addr"])
    if rc != 0:
        return Needles(pairs, "lima guest (unreachable)")
    head, _, links = out.partition("\n1:")
    for line in head.splitlines():
        line = line.strip()
        if len(line) >= MIN_LITERAL:
            pairs.append(("guest-identity", line))
    pairs += _ifconfig_needles(("1:" + links).replace("link/ether", "ether")
                               .replace("inet6", "inet6"))
    return Needles(pairs, "lima guest")


def count_needles(texts: Sequence[str],
                  needles: Needles) -> collections.Counter:
    """Occurrences per needle, keyed by fingerprint. Case-insensitive."""
    hits: collections.Counter = collections.Counter()
    lowered = [(kind, value.lower(), fingerprint(kind, value))
               for kind, value in needles]
    for text in texts:
        low = text.lower()
        for _, probe, fpr in lowered:
            n = low.count(probe)
            if n:
                hits[fpr] += n
    return hits



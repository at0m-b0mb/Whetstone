def generate(*, executor: Any, seed: int, repeats: int, observe: int,
             refusals: int, clean: int, remediate: int, include_lab: bool,
             lab: int, lab_root: Path | None,
             verbose: bool) -> tuple[list[str], dict[str, Any]]:
    """Run the real generator with *executor* driving the host worlds."""
    from training.trajectories import generate_trajectories

    stats: dict[str, Any] = {}
    texts = list(generate_trajectories(
        repeats=repeats, seed=seed, verbose=verbose, include_lab=include_lab,
        lab_root=lab_root, stats=stats, observe=observe, refusals=refusals,
        lab=lab, clean=clean, remediate=remediate, host_executor=executor))
    return texts, stats


def coverage() -> dict[str, Any]:
    """What the VM adapter can and cannot do, measured from the adapter.

    ``docs/ROADMAP.md`` says ``lab/vm/adapter.py`` implements no ``harden.*``
    verbs and that remediation against the VM is therefore always
    ``unavailable``. **That is stale.** The adapter implements all three, and
    this function asks it rather than reading the roadmap — which is this
    codebase's most expensive lesson: three measurement bugs here each accused
    the model and all three were in the ruler.
    """
    from lab.vm.adapter import VMAdapter
    from whetstone.adapters.base import get_adapter

    vm = set(VMAdapter.implemented(VMAdapter.__new__(VMAdapter)))
    host = set(get_adapter().implemented())
    return {
        "vm": sorted(vm),
        "host": sorted(host),
        "host_platform": get_adapter().platform,
        "missing": sorted(host - vm),
        "vm_harden": sorted(v for v in vm if v.startswith("harden.")),
        "host_harden": sorted(v for v in host if v.startswith("harden.")),
    }


def verbs_exercised(texts: Sequence[str]
                    ) -> tuple[collections.Counter, collections.Counter]:
    """Verbs proposed, and verbs that actually returned an observation.

    Two counters because they answer different questions and the difference is
    the coverage limit. The plan chooser proposes the same verbs against either
    executor, so *proposed* is identical in both batches and says nothing; a
    verb the VM adapter does not implement comes back as an error rather than
    an observation, so *succeeded* is where an 18-verb gap becomes visible.
    """
    proposed: collections.Counter = collections.Counter()
    succeeded: collections.Counter = collections.Counter()
    for text in texts:
        parts = SEGMENT.split(text)
        pending: str | None = None
        for i in range(1, len(parts) - 1, 2):
            name, body = parts[i], parts[i + 1].strip()
            if name == "act":
                pending = None
                try:
                    act = json.loads(body)
                except json.JSONDecodeError:
                    continue
                if isinstance(act, dict) and isinstance(act.get("verb"), str):
                    proposed[act["verb"]] += 1
                    pending = act["verb"]
            elif name == "obs" and pending:
                try:
                    obs = json.loads(body)
                except json.JSONDecodeError:
                    pending = None
                    continue
                if isinstance(obs, dict) and obs.get("ok") is True:
                    succeeded[pending] += 1
                pending = None
            elif name in {"gate", "find"}:
                pending = pending if name == "gate" else None
    return proposed, succeeded



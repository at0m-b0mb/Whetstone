def _render_hits(label: str, hits: collections.Counter, needles: Needles,
                 documents: int) -> None:
    total = sum(hits.values())
    tint = C["r"] if total else C["g"]
    per = f"  ({total / documents:.2f}/doc)" if documents else ""
    print(f"  {label:<26}{tint}{total:>8,}{C['x']} occurrences over "
          f"{len(hits)} of {len(needles)} needles{per}")
    for fpr, count in hits.most_common(10):
        print(f"      {C['dim']}{fpr:<44}{count:>8,}{C['x']}")


def report(label: str, texts: Sequence[str], *, host: Needles,
           guest: Needles | None, consts: set[str], blob: str) -> Spread:
    print(f"\n{C['b']}{C['c']}{label}{C['x']}")
    sp = spread(texts, consts=consts, blob=blob)
    print(f"  {'documents':<26}{sp.documents:>8,}  {sp.chars:,} chars")
    print(f"  {'segments parsed':<26}{sp.segments:>8,}  "
          f"{sp.malformed} malformed")
    _render_hits("host identifiers", count_needles(texts, host), host,
                 sp.documents)
    if guest is not None:
        _render_hits("guest identifiers", count_needles(texts, guest), guest,
                     sp.documents)
    print(f"  {'distinct leaf literals':<26}{sp.distinct:>8,}  "
          f"({sp.occurrences:,} occurrences)")
    print(f"  {'of those host-read':<26}{sp.host_distinct:>8,}  "
          f"({sp.host_occurrences:,} occurrences, mean "
          f"{sp.mean_repetition:.1f}x)")
    if sp.top:
        print(f"  {'MAX host doc frequency':<26}{sp.max_docfreq:>7.2f}%  "
              f"{sp.max_docfreq_fp}")
        for fpr, docs, occ in sp.top[:6]:
            print(f"      {C['dim']}{fpr:<44}{docs:>6} docs {occ:>6} occ{C['x']}")
    else:
        print(f"  {'MAX host doc frequency':<26}{C['g']}{'none':>8}{C['x']}  "
              "every literal in this batch is authored in the source tree")
    return sp


def _delta(name: str, mac: float, vm: float, unit: str = "", *,
           good: str = "lower") -> None:
    """One row of the A/B. ``mac`` is the control, ``vm`` the change.

    ``good`` is not decoration. On the privacy and generalisation rows a
    smaller number is the win; on the coverage rows a smaller number is
    documents and verbs the VM batch does not contain, and colouring that
    green would be the report congratulating itself for losing data.

    ``mac == 0 and vm > 0`` prints INTRODUCED and never a percentage: a change
    from nothing to something has no ratio, and printing one gives a number
    that reads as small.
    """
    if mac == 0 and vm == 0:
        verdict = f"{C['dim']}both zero{C['x']}"
    elif mac == 0:
        verdict = (f"{C['r']}INTRODUCED{C['x']}" if good == "lower"
                   else f"{C['g']}INTRODUCED{C['x']}")
    elif vm == mac:
        verdict = f"{C['y']}unchanged{C['x']}"
    else:
        better = (vm < mac) if good == "lower" else (vm > mac)
        tint = C["g"] if better else C["r"]
        if vm == 0:
            verdict = f"{tint}eliminated{C['x']}"
        else:
            pct = 100 * (vm / mac - 1)
            verdict = f"{tint}{pct:+.0f}%{C['x']}"
    print(f"  {name:<30}{mac:>12,.2f}{unit}{vm:>14,.2f}{unit}   {verdict}")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Generate trajectories against the Lima VM and measure "
                    "the privacy and generalisation win separately.")
    p.add_argument("--out", type=Path,
                   help="write trajectory-NNNNN.txt here (refuses a directory "
                        "that already holds any)")
    p.add_argument("--measure", action="store_true",
                   help="generate a small batch both ways and report; writes "
                        "nothing")
    p.add_argument("--no-mac", action="store_true",
                   help="skip the Mac-generated control batch")
    p.add_argument("--repeats", type=int, default=2)
    p.add_argument("--seed", type=int, default=1337)
    p.add_argument("--observe", type=int, default=24)
    p.add_argument("--refusals", type=int, default=12)
    p.add_argument("--clean", type=int, default=0)
    p.add_argument("--remediate", type=int, default=0)
    p.add_argument("--lab", type=int, default=0)
    p.add_argument("--with-lab", action="store_true",
                   help="include the sandbox worlds. They do not run against "
                        "the VM, so a measurement run leaves them out: they "
                        "would be identical in both batches and dilute the "
                        "only difference being measured")
    p.add_argument("--lab-root", type=Path)
    p.add_argument("--no-start", action="store_true",
                   help="fail rather than start a stopped VM")
    p.add_argument("--no-truncate", action="store_true",
                   help="leave the guest audit log alone (stale records then "
                        "read as this run's detections)")
    p.add_argument("--no-arm", action="store_true",
                   help="do not load the auditd file watch")
    p.add_argument("--verbose", action="store_true")
    args = p.parse_args(argv)

    if not args.measure and not args.out:
        p.error("give --measure, or --out to write a generation")

    print(f"\n{C['b']}{C['c']}regenerate trajectories — off this Mac{C['x']}")
    host = host_needles()
    print(f"{C['dim']}host needles: {host!r} (runtime-derived, never "
          f"written){C['x']}")

    state = ensure_vm(start=not args.no_start)
    print(f"{C['dim']}LIMA_HOME={LIMA_HOME}  instance={VM_NAME}  "
          f"state={state}{C['x']}")
    guest = guest_needles()
    print(f"{C['dim']}guest needles: {guest!r}{C['x']}")

    cov = coverage()
    print(f"\n{C['b']}adapter coverage{C['x']}")
    print(f"  VM implements {len(cov['vm'])} verbs; the {cov['host_platform']} "
          f"adapter implements {len(cov['host'])}")
    print(f"  harden on the VM:   {', '.join(cov['vm_harden']) or 'none'}")
    print(f"  harden on the host: {', '.join(cov['host_harden']) or 'none'}")
    if cov["vm_harden"]:
        print(f"  {C['y']}docs/ROADMAP.md says the VM adapter implements no "
              f"harden.* verbs. Measured from implemented(), it implements "
              f"{len(cov['vm_harden'])}. The roadmap is stale.{C['x']}")
    print(f"  {C['r']}missing on the VM ({len(cov['missing'])}): "
          f"{', '.join(cov['missing'])}{C['x']}")
    leaky = [v for v in cov["missing"]
             if v in {"enum.network", "enum.software", "enum.users",
                      "enum.persistence", "enum.shares"}]
    if leaky:
        print(f"  {C['y']}and those include {', '.join(leaky)} — the verbs "
              f"that produced every network, inventory and display-name leak "
              f"the audit found. A VM batch is not the same corpus from "
              f"another machine; it is a NARROWER corpus.{C['x']}")

    pf = preflight(truncate=not args.no_truncate, arm=not args.no_arm)
    print(f"\n{C['b']}guest preflight{C['x']}")
    print(f"  clock skew (guest - host)   {pf.clock_skew:+d}s")
    print(f"  newest audit record         {pf.record_skew:+.0f}s from the "
          f"guest's own clock")
    print(f"  audit log before            {pf.log_bytes_before:,} bytes"
          + ("  truncated" if pf.truncated else "  NOT truncated"))
    print(f"  file watch loaded           {pf.rule_loaded}")
    for note in pf.notes:
        print(f"  {C['y']}{note}{C['x']}")

    kw = dict(seed=args.seed, repeats=args.repeats, observe=args.observe,
              refusals=args.refusals, clean=args.clean,
              remediate=args.remediate, include_lab=args.with_lab,
              lab=args.lab, lab_root=args.lab_root, verbose=args.verbose)
    consts, blob = authored_literals()
    print(f"\n{C['dim']}structure/content discriminator: "
          f"{len(consts):,} authored string constants, "
          f"{len(blob):,} chars of source{C['x']}")

    from lab.vm.adapter import VMAdapter

    t0 = time.time()
    vm_texts, vm_stats = generate(executor=VMAdapter(), **kw)
    vm_secs = time.time() - t0
    vm_sp = report(f"VM ({VM_NAME}) — {vm_secs:.1f}s", vm_texts, host=host,
                   guest=guest, consts=consts, blob=blob)

    mac_sp = None
    if not args.no_mac:
        t0 = time.time()
        mac_texts, _ = generate(executor=None, **kw)
        mac_secs = time.time() - t0
        mac_sp = report(f"MAC (this machine) — {mac_secs:.1f}s", mac_texts,
                        host=host, guest=guest, consts=consts, blob=blob)

        print(f"\n{C['b']}the two axes{C['x']}")
        print(f"  {'':<30}{'mac':>14}{'vm':>16}")
        mac_hits = sum(count_needles(mac_texts, host).values())
        vm_hits = sum(count_needles(vm_texts, host).values())
        _delta("PRIVACY host needle occ", mac_hits, vm_hits)
        _delta("PRIVACY guest needle occ",
               sum(count_needles(mac_texts, guest).values()),
               sum(count_needles(vm_texts, guest).values()))
        _delta("GENERALISE host distinct", mac_sp.host_distinct,
               vm_sp.host_distinct)
        _delta("GENERALISE mean repetition", mac_sp.mean_repetition,
               vm_sp.mean_repetition, "x")
        _delta("GENERALISE max docfreq", mac_sp.max_docfreq,
               vm_sp.max_docfreq, "%")
        _delta("COVERAGE documents", mac_sp.documents, vm_sp.documents,
               good="higher")
        _delta("COVERAGE chars", mac_sp.chars, vm_sp.chars, good="higher")
        mac_proposed, mac_ok = verbs_exercised(mac_texts)
        vm_proposed, vm_ok = verbs_exercised(vm_texts)
        _delta("COVERAGE verbs proposed", len(mac_proposed), len(vm_proposed),
               good="higher")
        _delta("COVERAGE verbs observed", len(mac_ok), len(vm_ok), good="higher")
        lost = sorted(set(mac_ok) - set(vm_ok))
        if lost:
            print(f"  {C['y']}verbs that returned an observation on the Mac "
                  f"and not on the VM ({len(lost)}): {', '.join(lost)}{C['x']}")
        if vm_hits == 0 and vm_sp.host_distinct:
            print(f"\n  {C['y']}Read this carefully. Host needles went to "
                  f"zero, so the privacy axis is satisfied. But the VM batch "
                  f"still carries {vm_sp.host_distinct} host-read literals at "
                  f"up to {vm_sp.max_docfreq:.1f}% document frequency — the "
                  f"guest's. Swapping which machine leaks is progress on "
                  f"privacy and not on generalisation: it is still ONE "
                  f"machine.{C['x']}")

    if vm_stats.get("errors"):
        print(f"\n{C['b']}generator errors{C['x']}")
        for name, count in sorted(vm_stats["errors"].items()):
            print(f"  {count:,}x {name}")
    for label, count in sorted(vm_stats.get("fix_mismatch", {}).items()):
        print(f"  {C['r']}MISMATCH {count:,}x {label}{C['x']}")

    if args.out:
        hits = count_needles(vm_texts, host)
        if hits:
            print(f"\n{C['r']}REFUSING to write: {sum(hits.values()):,} host "
                  f"needle occurrences in the generated batch. Fingerprints "
                  f"above. Nothing was written.{C['x']}")
            return 1
        n = write_trajectories(args.out, vm_texts)
        print(f"\n{n:,} trajectories -> {args.out}")
        print(f"  {C['dim']}host needles: 0. Guest needles: "
              f"{sum(count_needles(vm_texts, guest).values()):,} — the VM's "
              f"own, not his.{C['x']}")
    elif args.measure:
        print(f"\n{C['y']}MEASURE ONLY — nothing written.{C['x']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

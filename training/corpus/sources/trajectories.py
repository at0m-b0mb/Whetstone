"""Agent trajectories — the TRAJECTORY register, and the only one we generate.

Every other source in this corpus is collected. This one is *produced*, by
running the real agent against this machine and recording what happened: real
actions the registry bound, real observations real adapters returned from real
commands, real rulings from the real gate.

It exists because the benchmark said so. ``action-json`` scored 0/5 — the model
could not emit an action the registry would accept — and the reason was not
capacity but curriculum: the corpus had no trajectory data at all, so the
protocol tokens sat in the vocabulary reserved and unused. The model had learned
the language of security and had never seen the job.

**Why this is not synthetic data.** The distinction matters more here than
almost anywhere else in the corpus. It would be easy to write plausible
observations by hand, and the result would train a model to predict what tool
output *looks like* rather than what this tool *returns* — a difference that
stays invisible until something is wired to a live host and answers confidently
about a machine it misread. Regenerate this source on a different machine and
the observations change, because they are observations.

Generated by :mod:`training.trajectories`; run that first. The raw cache is not
redistributable as a blob: it contains this machine's service list, account
names and network state.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Iterator

from ..source import Document, Register, Side, SourceError, SourceSpec, normalise

_MIN_CHARS = 200


def _fetch(cache_dir: Path) -> Path:
    """No download and no generation: trajectories are produced deliberately.

    This does *not* generate on demand. Producing training data as a side effect
    of a corpus build would mean every build silently runs commands against the
    host it is building on, which is a surprising thing for a build to do and
    exactly the sort of implicit behaviour this project avoids elsewhere. Run
    ``python -m training.trajectories`` when you mean to.
    """
    cache_dir.mkdir(parents=True, exist_ok=True)
    if not any(cache_dir.glob("trajectory-*.txt")):
        raise SourceError(
            f"no trajectories under {cache_dir}. Generate them first:\n"
            "    python3 -m training.trajectories --repeats 8\n"
            "This source is produced by running the real agent, not downloaded, "
            "and it is not generated implicitly by a corpus build."
        )
    return cache_dir


def _documents(path: Path) -> Iterator[Document]:
    for dirpath, dirnames, filenames in os.walk(path, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames
                             if not Path(dirpath, d).is_symlink())
        for filename in sorted(filenames):
            if not filename.startswith("trajectory-") or not filename.endswith(".txt"):
                continue
            file = Path(dirpath, filename)
            if file.is_symlink():
                continue
            try:
                raw = file.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            text = normalise(raw)
            if len(text) < _MIN_CHARS:
                continue
            yield Document(text=text, source="trajectories",
                           register=Register.TRAJECTORY, side=Side.NEUTRAL,
                           ident=file.stem)


SPEC = SourceSpec(
    name="trajectories",
    license=("Generated locally by this repository (MIT) from this machine's own "
             "state. Contains host-specific service, account and network detail; "
             "the raw cache is NOT redistributable."),
    url="local: python3 -m training.trajectories",
    register=Register.TRAJECTORY,
    side=Side.NEUTRAL,
    fetch=_fetch,
    documents=_documents,
    expect_min_docs=200,
    notes=("The only produced source. Real actions, real observations, real gate "
           "rulings — including refusals followed by recovery, which is the half "
           "of agent behaviour a success-only corpus never teaches."),
)
